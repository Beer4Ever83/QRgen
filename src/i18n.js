export function t(lang, key, params = {}) {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, name) => params[name]);
}

export function resolveLanguage(value) {
  return LANGUAGES.includes(value) ? value : DEFAULT_LANGUAGE;
}
